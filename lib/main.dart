Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await loadPalette();
  runApp(const MilkApp());
}

class MilkApp extends StatelessWidget {
  const MilkApp({super.key});
  @override
  Widget build(BuildContext context) => ValueListenableBuilder<int>(
        valueListenable: paletteIndex,
        builder: (_, i, __) => MaterialApp(
          title: 'Milk App',
          theme: themeFor(palettes[i]),
          home: StreamBuilder<User?>(
            stream: FirebaseAuth.instance.authStateChanges(),
            builder: (c, s) {
              if (s.connectionState == ConnectionState.waiting) {
                return const Scaffold(body: Center(child: CircularProgressIndicator()));
              }
              final u = s.data;
              return u == null ? const LoginPage() : RoleRouter(phone: u.phoneNumber ?? '');
            },
          ),
        ),
      );
}

class RoleRouter extends StatefulWidget {
  final String phone;
  const RoleRouter({super.key, required this.phone});
  @override
  State<RoleRouter> createState() => _RoleRouterState();
}

class _RoleRouterState extends State<RoleRouter> {
  late final Future<Widget> f = resolve();
  Future<Widget> resolve() async {
    final p = widget.phone;
    final s = await db.collection('staff').doc(p).get();
    if (s.exists) {
      final m = s.data()!;
      if (m['role'] == 'admin') return const AdminHome();
      return DeliveryHome(route: (m['route'] ?? '') as String);
    }
    final c = await db.collection('customers').where('phone', isEqualTo: p).limit(1).get();
    if (c.docs.isNotEmpty) return CustomerHome(phone: p);
    return Scaffold(
      appBar: AppBar(actions: topActions()),
      body: Center(child: Text('$p is not registered.\nAsk the dairy to add your number.', textAlign: TextAlign.center)),
    );
  }

  @override
  Widget build(BuildContext context) => FutureBuilder<Widget>(
        future: f,
        builder: (c, s) => s.hasData
            ? s.data!
            : Scaffold(
                body: Center(
                    child: s.hasError ? Text('${s.error}') : const CircularProgressIndicator())),
      );
}

class LoginPage extends StatefulWidget {
  const LoginPage({super.key});
  @override
  State<LoginPage> createState() => _LoginPageState();
}

class _LoginPageState extends State<LoginPage> {
  final ph = TextEditingController(), otp = TextEditingController();
  String? vid, err;
  bool busy = false;

  void send() {
    setState(() { busy = true; err = null; });
    FirebaseAuth.instance.verifyPhoneNumber(
      phoneNumber: normPhone(ph.text),
      verificationCompleted: (cred) => FirebaseAuth.instance.signInWithCredential(cred),
      verificationFailed: (e) => setState(() { busy = false; err = e.message; }),
      codeSent: (id, _) => setState(() { vid = id; busy = false; }),
      codeAutoRetrievalTimeout: (_) {},
    );
  }

  Future<void> verify() async {
    setState(() { busy = true; err = null; });
    try {
      await FirebaseAuth.instance.signInWithCredential(
          PhoneAuthProvider.credential(verificationId: vid!, smsCode: otp.text.trim()));
    } on FirebaseAuthException catch (e) {
      setState(() { busy = false; err = e.message; });
    }
  }

  @override
  Widget build(BuildContext context) => Scaffold(
        body: Column(children: [
          bannerImage(height: 190),
          Expanded(
            child: Center(
              child: SingleChildScrollView(
                padding: const EdgeInsets.all(24),
                child: Column(mainAxisSize: MainAxisSize.min, children: [
              Image.asset('assets/images/logo.png', height: 72),
              const SizedBox(height: 4),
              Text('Milk Delivery', style: Theme.of(context).textTheme.titleLarge),
              const SizedBox(height: 16),
              if (vid == null) ...[
                TextField(
                    controller: ph,
                    keyboardType: TextInputType.phone,
                    decoration: const InputDecoration(labelText: 'Mobile number', prefixText: '+91 ')),
                const SizedBox(height: 16),
                FilledButton(onPressed: busy ? null : send, child: const Text('Send OTP')),
              ] else ...[
                TextField(
                    controller: otp,
                    keyboardType: TextInputType.number,
                    decoration: const InputDecoration(labelText: 'OTP')),
                const SizedBox(height: 16),
                FilledButton(onPressed: busy ? null : verify, child: const Text('Verify')),
              ],
              if (err != null) Padding(padding: const EdgeInsets.only(top: 12), child: Text(err!, style: const TextStyle(color: Colors.red))),
                ]),
              ),
            ),
          ),
        ]),
      );
}
